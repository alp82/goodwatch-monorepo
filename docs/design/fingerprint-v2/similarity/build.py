"""Build the design mapping and inspect saved assessments; never fill missing scores.

Run from any directory. --assessment LABEL=PATH may be repeated for saved
draft.2 assessment.json files. This is a design tool, not a production publisher.
"""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(name, value):
    (HERE / name).write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")


def build():
    source = HERE.parent / "definition.json"
    definition = json.loads(source.read_text())
    policy = json.loads((HERE / "selection.json").read_text())
    groups = definition["attribute_groups"]
    assert set(groups) == set(policy["groups"])
    rows, order = [], []
    context_fields = {
        "world_treatment.lore_dependence", "sound.nonmusical_sound_dependence",
        "ending.sequel_dependence",
    }
    for group, attrs in groups.items():
        rule = policy["groups"][group]
        chosen = rule["include"]
        chosen = list(attrs) if chosen == "*" else chosen.split() if isinstance(chosen, str) else chosen
        assert len(chosen) == len(set(chosen)) and set(chosen) <= set(attrs), group
        for key, spec in attrs.items():
            field = f"{group}.{key}"
            selected = key in chosen
            destination = "fingerprint" if selected else "content_metadata"
            if not selected:
                if group == "evaluations":
                    destination = "evaluations"
                elif group in {"viewing_demands", "viewing_affordances"} or field in context_fields:
                    destination = "viewing_context"
                elif group == "series":
                    destination = "series_metadata"
            if selected:
                assert spec["applicability"] == "all", field
                order.append(field)
            rows.append({
                "field": field, "destination": destination,
                "vector_index": len(order) - 1 if selected else None,
                "measurement": spec["measurement"], "applicability": spec["applicability"],
                "spoiler_sensitive": spec["spoiler_sensitive"],
                "original_similarity_role": spec["similarity_role"],
                "reason": rule["reason"] if selected or not chosen else rule["excluded_reason"],
            })
    assert len(rows) == 554 and len({r["field"] for r in rows}) == 554
    counts = dict(Counter(r["destination"] for r in rows))
    mapping = {
        "version": policy["version"], "status": policy["status"],
        "registry_version": definition["version"], "registry_sha256": digest(source),
        "selection_sha256": digest(HERE / "selection.json"),
        "counts": counts, "dimension_count": len(order), "ordered_fields": order,
        "indexing_contract": {
            "value_type": "integer", "minimum": 0, "maximum": 10,
            "required_numeric_dimensions": len(order), "unknown_to_zero": False,
            "per_title_dimension_selection": False,
            "metric_and_weights": "Unselected; this mapping does not authorize unweighted flattening or deployment.",
            "additional_gate": "Resolve validation/consistency failures affecting selected fields; numeric completeness alone is not quality acceptance.",
        },
        "other_outputs": {
            "content_presence": "All 146 entries remain metadata with explicit unknowns; none is a numeric vector coordinate.",
            "advisories": "Separate safety/content contract; never infer verified absence from centrality zero.",
            "explanations": "Essence, tags, evidence, highlights and confidence remain outside vector distance.",
        },
        "fields": rows,
    }
    write_json("mapping.json", mapping)
    lines = ["# Attribute placement", "", "Generated by `build.py` from `selection.json` and the unchanged draft.2 registry.", "",
             "Every one of the 554 numeric attributes has one primary destination. Metadata can still support targeted retrieval. All indices are zero-based.", ""]
    for group in groups:
        lines += [f"## {group}", "", "| Field | Destination | Vector index |", "|---|---|---:|"]
        lines += [f"| `{r['field']}` | {r['destination']} | {r['vector_index'] if r['vector_index'] is not None else '—'} |" for r in rows if r['field'].startswith(group + '.')]
        lines += ["", policy['groups'][group]['reason'], ""]
        if 'excluded_reason' in policy['groups'][group]:
            lines += ["Excluded subfields: " + policy['groups'][group]['excluded_reason'], ""]
    (HERE / "attribute-placement.md").write_text("\n".join(lines))
    return mapping


def inspect(mapping, supplied):
    results = []
    known = {r['field'] for r in mapping['fields']}
    for argument in supplied:
        label, filename = argument.split("=", 1)
        path = Path(filename)
        assessment = json.loads(path.read_text())
        values = assessment['comparable_values']
        assert set(values) == known, f"{label}: incompatible field set"
        state_counts, missing, per_group = Counter(), [], {}
        for field in mapping['ordered_fields']:
            value = values[field]
            state = 'numeric' if type(value) is int and 0 <= value <= 10 else 'null' if value is None else 'invalid'
            state_counts[state] += 1
            group = field.split('.')[0]
            per_group.setdefault(group, Counter())[state] += 1
            if state != 'numeric':
                missing.append({'field': field, 'state': state, 'retained_state': assessment.get('numeric_states', {}).get(field)})
        results.append({
            'label': label, 'assessment_sha256': digest(path),
            'selected_count': mapping['dimension_count'], 'counts': dict(state_counts),
            'numeric_complete': not missing,
            'quality_accepted': False,
            'per_group': {k: dict(v) for k, v in per_group.items()},
            'unavailable_selected_fields': missing,
        })
    write_json('coverage.json', {
        'projection_version': mapping['version'], 'registry_sha256': mapping['registry_sha256'],
        'mapping_sha256': digest(HERE / 'mapping.json'),
        'scope': 'Saved draft.2 assessments only. No new inference, imputation or semantic rejudging. Completeness is not correctness.',
        'results': results,
    })
    return results


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--assessment', action='append', default=[])
    args = parser.parse_args()
    mapping = build()
    print(json.dumps(mapping['counts']))
    if args.assessment:
        for result in inspect(mapping, args.assessment):
            print(result['label'], result['counts'])
