from ev import *
W = dict(out='shape', parts='p', strict=True, tie=True, eps=0.03)
LIN = 'L2+Ren+Rtags'; FP = dict(v='Tm', lin=LIN, fr=True)
def pr(name, a, b):
    for conv, kw in (('cont', dict(out='cont')), ('shape', W)):
        print(cline(f'{name} [{conv}]', compare(preds(**kw, **a), preds(**kw, **b))), flush=True)
print(f"{'name':46s} mae   macro rho   bad  auc   | skill rho_others")
for nm, kw in (('baseline A', dict(v='A')), ('final point FP', FP)):
    print(line(nm + ' cont', preds(out='cont', **kw))); print(line(nm + ' round', preds(out='round', **kw)))
    for a in (0.5, 0.75): print(line(f'{nm} shape a={a}', preds(alpha=a, **W, **kw)), flush=True)
print('--- ladder: each step vs the one before (negative mae/macro = better)')
pr('1 +text columns in trees', dict(v='A'), dict(v='T'))
pr('2 +monotone scores, column sampling', dict(v='T'), dict(v='Tm'))
pr('3 +linear stack', dict(v='Tm'), dict(v='Tm', lin=LIN))
pr('4 +franchise stage', dict(v='Tm', lin=LIN), FP)
print('--- drop one from the final (final minus variant-without)')
pr('text columns', dict(v='Am', lin=LIN, fr=True), FP)
pr('monotone + column sampling', dict(v='T', lin=LIN, fr=True), FP)
pr('linear stack', dict(v='Tm', fr=True), FP)
pr('  of which embedding+tag ridges', dict(v='Tm', lin='L2', fr=True), FP)
pr('franchise stage', dict(v='Tm', lin=LIN), FP)
print('--- tried on top of the final and dropped (variant minus final)')
