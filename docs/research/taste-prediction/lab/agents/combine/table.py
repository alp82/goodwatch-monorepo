pr('metric kernel instead of 2-stage linear', FP, dict(v='Tm', lin='MK+Ren+Rtags', fr=True))
pr('plain 50/50 blend with metric kernel', FP, dict(v='Tm', lin='half', fr=True))
print(cline('tree+logit dists in the shape (tlp, dv=T)', compare(preds(**W, **FP), preds(out='shape', parts='tlp', dv='T', tie=True, **FP))), flush=True)
print('--- output shape on the final point predictor')
print(cline('round vs cont', compare(preds(out='cont', **FP), preds(out='round', **FP))))
print(cline('shape a=.5 vs round', compare(preds(out='round', **FP), preds(**W, **FP))))
print(cline('shape a=.75 vs shape a=.5', compare(preds(**W, **FP), preds(alpha=.75, **W, **FP))), flush=True)
print('--- final vs baseline, same convention')
print(cline('cont vs cont', compare(preds(out='cont', v='A'), preds(out='cont', **FP))))
print(cline('round vs round', compare(preds(out='round', v='A'), preds(out='round', **FP))))
