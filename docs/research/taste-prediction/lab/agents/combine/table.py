print(cline('shape.5 vs badscores-like shape.5', compare(preds(out='shape', v='Ao', dv='A', parts='tlp'), preds(**W, **FP))))
print(cline('shape.5 vs baseline cont (as shipped)', compare(preds(out='cont', v='A'), preds(**W, **FP))))
print(cline('shape.75 vs baseline cont (as shipped)', compare(preds(out='cont', v='A'), preds(alpha=.75, **W, **FP))))
