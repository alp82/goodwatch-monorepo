// A small browser walkthrough for the throwaway prototype, with all remote requests intercepted.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const require=createRequire(process.env.PLAYWRIGHT ?? '/usr/lib/node_modules/@playwright/cli/node_modules/playwright-core/package.json')
const {chromium}=require('playwright-core')
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox']})
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
page.setDefaultTimeout(30000)
const checks=[],mutations=[],errors=[]
const origin='http://127.0.0.1:3114'
await page.route('**/*',async route=>{const request=route.request(),url=new URL(request.url());if(url.origin!==origin || url.pathname==='/api/e') return route.fulfill({status:200,contentType:'application/json',body:'{}'});if(request.method()!=='GET')mutations.push(request.method()+' '+url.pathname);return route.continue()})
page.on('pageerror',e=>errors.push(e.message))
const surface=page.locator('.ap-surface')
async function open(screen,variant='A',state='default') {await page.goto(`${origin}/prototype/auth?screen=${screen}&variant=${variant}&state=${state}`,{waitUntil:'load',timeout:120000});await surface.locator('h1').waitFor();await page.locator('.ap-switcher').waitFor()}
async function check(name,locator){await locator.waitFor();checks.push(name)}
await open('sign-in')
await surface.getByLabel('Password',{exact:true}).fill('usual-password')
await surface.getByRole('button',{name:'Show password',exact:true}).click()
if(await surface.getByLabel('Password',{exact:true}).getAttribute('type')!=='text')throw Error('Password show failed')
checks.push('Show password')
await surface.getByRole('button',{name:'Sign in',exact:true}).click()
await check('Email sign-in succeeds locally',surface.getByRole('heading',{name:"You're signed in",exact:true}))
await open('sign-in','A','error')
await surface.getByLabel('Password',{exact:true}).fill('wrong-password')
await surface.getByRole('button',{name:'Sign in',exact:true}).click()
await check('Bad sign-in copy',surface.getByRole('alert'))
await surface.getByRole('button',{name:'Forgot password?'}).click()
await check('Forgot password navigation',surface.getByRole('heading',{name:'Forgot your password?'}))
await surface.getByRole('button',{name:'Send reset link'}).click()
await check('Reset request acknowledgement',surface.getByRole('heading',{name:'Check your inbox'}))
await open('reset-new')
await surface.getByLabel('New password',{exact:true}).fill('a long new password')
await surface.getByLabel('Confirm new password',{exact:true}).fill('a different password')
await surface.getByRole('button',{name:'Update password'}).click()
await check('Password mismatch',surface.getByRole('alert'))
await surface.getByLabel('Confirm new password',{exact:true}).fill('a long new password')
await surface.getByRole('button',{name:'Update password'}).click()
await check('Password update completion',surface.getByRole('heading',{name:'Password updated'}))
await surface.getByRole('button',{name:'Sign in',exact:true}).click()
await check('Reset completion returns to sign-in',surface.getByRole('heading',{name:'Good to have you back'}))
await open('reset-new','A','expired')
await surface.getByRole('button',{name:'Get a new reset link'}).click()
await check('Expired reset recovery',surface.getByRole('heading',{name:'Forgot your password?'}))
await open('sign-up','B')
await surface.getByLabel('New password',{exact:true}).fill('a long new password')
await surface.getByRole('button',{name:'Create account',exact:true}).click()
await check('Sign-up opens verification',surface.getByRole('heading',{name:'Check your email'}))
await surface.getByRole('button',{name:'Resend verification email'}).click()
await check('Verification resend acknowledgement',surface.getByText('Verification email sent. Check your inbox.',{exact:true}))
if(!await surface.getByRole('button',{name:/Email sent · wait/}).isDisabled())throw Error('Resend not limited')
checks.push('Visible resend cooldown')
await open('verify','A','success')
await surface.getByRole('button',{name:'Back to sign in'}).click()
await check('Verification completion returns to sign-in',surface.getByRole('heading',{name:'Good to have you back'}))
await open('cutover','B')
await surface.getByRole('button',{name:'Sign in again'}).click()
await check('Cut-over continues to sign-in',surface.getByRole('heading',{name:'Good to have you back'}))
await page.getByRole('navigation',{name:'Prototype screens'}).getByRole('button',{name:'Cut-over'}).click()
if(await surface.getByText('Same GoodWatch.',{exact:false}).count())throw Error('Cut-over did not dismiss')
checks.push('Cut-over shown once within demo session')
await open('sign-in')
await surface.getByRole('button',{name:'Continue with Google'}).click()
await check('Google sign-in is simulated locally',surface.getByRole('heading',{name:'Signed in with Google'}))
await open('consent','B')
await surface.getByRole('button',{name:'Use another account'}).click()
await check('Consent account switch resumes through sign-in',surface.getByText('Sign in to connect Claude. You’ll review access next.'))
await surface.getByRole('button',{name:'Continue with Google'}).click()
await check('Sign-in returns to pending consent',surface.getByRole('heading',{name:'Claude wants to access your GoodWatch'}))
await surface.getByRole('button',{name:'Cancel',exact:true}).click()
await check('Consent cancellation',surface.getByRole('heading',{name:'Connection cancelled'}))
await open('consent')
await surface.getByRole('button',{name:'Allow access'}).click()
await check('Consent approval',surface.getByRole('heading',{name:'Claude is connected'}))
await surface.getByRole('button',{name:'View connected apps'}).click()
await surface.getByRole('button',{name:'Disconnect Claude'}).click()
await check('Disconnect asks for confirmation',page.getByRole('dialog'))
await page.getByRole('dialog').getByRole('button',{name:'Keep connected'}).click()
await check('Cancel disconnect retains app',surface.getByRole('heading',{name:'Claude',exact:true}))
await surface.getByRole('button',{name:'Disconnect Claude'}).click()
await page.getByRole('dialog').getByRole('button',{name:'Disconnect',exact:true}).click()
if(await surface.getByRole('heading',{name:'Claude',exact:true}).count())throw Error('App remains connected')
checks.push('Disconnect removes app in memory')
await surface.getByRole('button',{name:'View access'}).click()
await surface.getByRole('button',{name:'Disconnect ChatGPT'}).click()
await page.getByRole('dialog').getByRole('button',{name:'Disconnect',exact:true}).click()
await check('Disconnect final app gives empty list',surface.getByRole('heading',{name:'No apps connected'}))
await open('sign-in')
await page.locator('.ap-switcher').getByRole('button',{name:'Next variant'}).click()
await page.waitForURL('**variant=B*')
await check('Variant changes structure and URL',surface.getByRole('heading',{name:'Less searching. More watching.'}))
await surface.getByLabel('Email',{exact:true}).focus()
await page.keyboard.press('ArrowLeft')
if(!page.url().includes('variant=B'))throw Error('Variant switch intercepted text input')
checks.push('Arrow keys leave input editing alone')
await page.locator('.ap-workbench>span').click()
await page.keyboard.press('ArrowRight')
await page.waitForURL('**variant=A*')
checks.push('Keyboard variant switching')
await browser.close()
const result={checks,mutations,errors:[...new Set(errors)]}
writeFileSync(fileURLToPath(new URL('./verification.json',import.meta.url)),JSON.stringify(result,null,2)+'\n')
console.log(JSON.stringify(result,null,2))
if(mutations.length||errors.length)throw Error('Unexpected mutation or browser error')
