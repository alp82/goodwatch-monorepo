/**
 * The name of a kind, or null when it has none and shouldn't be shown. `placeKey` is the place's parts as
 * `family:slug` joined with "+", in the kit's sorted order. `only`: for movies and shows together, the one kind a
 * place really holds (Horror has movies only, Reality shows only): its clusters are that kind's, so its
 * hand-written names hold. A mixed place takes only names written for the mix; a name borrowed from the movies
 * would describe a different cluster.
 */
export function kindNameOf(
	kind: "movie" | "show" | "all",
	placeKey: string,
	id: string,
	only?: "movie" | "show",
): string | null {
	let hand = BY_HAND[`${kind}|${placeKey}|${id}`]
	if (hand === undefined && kind === "all" && only) hand = BY_HAND[`${only}|${placeKey}|${id}`]
	if (hand !== undefined) return hand
	return BY_TRAIT[id] ?? null
}
