/** Draws a G grid with its top-left at (x, y): solid pixels in c, edge pixels in edge (or c at half alpha). */
export function drawG(p, grid, x, y, c, edge, a = 1) {
  for (let r = 0; r < grid.length; r++) {
    const row = grid[r];
    for (let q = 0; q < row.length; q++) {
      const ch = row[q];
      if (ch === "#") p.dot(x + q, y + r, c, a);
      else if (ch === "+") edge === undefined ? p.dot(x + q, y + r, c, a * 0.5) : p.dot(x + q, y + r, edge, a);
    }
  }
}
