import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { MemoryDeletionStore, RECOVERY_MS, requireNotDeleting } from './proposal-deletion.ts';
import { ProposalService } from './proposal-service.server.ts';
import { ProposalMemoryRepository, proposalFixtureCatalog } from './proposal-test-support.ts';
import { RoomError } from './errors.ts';

const request = (nickname = 'Alex') => ({ contractVersion: 3 as const, commandId: randomBytes(16).toString('hex'), admissionSecret: randomBytes(32).toString('base64url'), nickname });
const who = (sessionId = 'session-1') => ({ userId: 'account-alex', sessionId, expiresAt: Date.now() + 86400_000 });
test('deletion retries preserve the original recovery deadline; a fresh authentication does not restore implicitly', async () => {
  const store = new MemoryDeletionStore();
  const subject = { kind: 'account' as const, userId: 'alex' };
  const first = await store.schedule(subject, 100);
  assert.equal(first.purgeAfter, 100 + RECOVERY_MS);
  assert.deepEqual(await store.schedule(subject, 900), first);
  await assert.rejects(requireNotDeleting(store, subject), /deletion is in progress/);
  await store.restore(subject, 1000);
  assert.equal(await store.get(subject), null);
});
test('expired recovery cannot race the purge claim; failed erasure retries without permitting restore', async () => {
  let attempts = 0;
  let finish: (() => void) | undefined;
  const store = new MemoryDeletionStore(async () => { attempts++; if (attempts === 1) throw Error('offline'); await new Promise<void>(resolve => { finish = resolve; }); });
  const subject = { kind: 'account' as const, userId: 'alex' };
  await store.schedule(subject, 10);
  await store.purgeDue(RECOVERY_MS);
  assert.equal(attempts, 0);
  await assert.rejects(store.purgeDue(10 + RECOVERY_MS), /offline/);
  assert.equal((await store.get(subject))?.phase, 'purging');
  await assert.rejects(store.restore(subject, 11 + RECOVERY_MS));
  const work = store.purgeDue(11 + RECOVERY_MS);
  await Promise.resolve(); finish!(); await work;
  assert.equal(await store.get(subject), null);
});
test('deleting YepWatch ends every room session, transfers hosting and fences account admissions, with explicit recovery', async () => {
  const repo = new ProposalMemoryRepository();
  const service = new ProposalService(repo, proposalFixtureCatalog, 'account-deletion-test-secret-at-least-thirty-two');
  const account = who();
  const host = await service.create(request(), account);
  const friend = await service.join(host.credential.roomId, { ...request('Mia'), inviteCode: host.invite.code });
  const id = host.credential.roomId;
  const second = await service.resumeAccount(id, who('session-2'));
  const state = await service.deleteAccount(account);
  assert.equal(state.phase, 'pending');
  const room = (await repo.read(id))!.room;
  const deleted = room.participants.find(p => p.memberUserId === account.userId)!;
  assert.ok(deleted.leftAt);
  assert.deepEqual(deleted.sessions, []);
  assert.equal(room.hostId, friend.credential.participantId);
  assert.equal(await service.accounts.sessionActive(account.sessionId), false);
  await assert.rejects(service.accountHome(who('new-sign-in')), /deletion is in progress/);
  await assert.rejects(service.create(request(), who('new-sign-in')), /deletion is in progress/);
  await assert.rejects(service.resumeAccount(id, who('new-sign-in'), true), /deletion is in progress/);
  await assert.rejects(service.read(id, { participantId: second.credential.participantId, token: second.credential.token, accountId: account.userId, sessionId: 'session-2' }), (e: unknown) => e instanceof RoomError);
  await service.deletions.restore({ kind: 'account', userId: account.userId }, Date.now());
  const recovered = await service.resumeAccount(id, who('new-sign-in'), true);
  assert.equal(recovered.credential.participantId, host.credential.participantId);
  assert.equal((await service.accountHome(who('new-sign-in'))).rooms.length, 1);
});
test('guest deletion rejects account participants and restores only a proven guest credential', async () => {
  const repo = new ProposalMemoryRepository();
  const service = new ProposalService(repo, proposalFixtureCatalog, 'guest-deletion-test-secret-at-least-thirty-two');
  const guest = await service.create(request());
  const access = { participantId: guest.credential.participantId, token: guest.credential.token };
  const id = guest.credential.roomId;
  await assert.rejects(service.deleteGuest(id, { ...access, token: 'wrong' }), /credential/);
  await service.deleteGuest(id, access);
  await assert.rejects(service.read(id, access), /left/);
  await service.restoreGuest(id, access);
  assert.equal((await service.read(id, access)).own.participantId, access.participantId);
  const member = await service.create(request(), who());
  await assert.rejects(service.deleteGuest(member.credential.roomId, { participantId: member.credential.participantId, token: member.credential.token, accountId: who().userId, sessionId: who().sessionId }), /account deletion/);
});
test("a command waits for the guest's deletion check that runs alongside its room read: refused, nothing committed, no replay", async () => {
  const repo = new ProposalMemoryRepository();
  const service = new ProposalService(repo, proposalFixtureCatalog, 'guest-deletion-test-secret-at-least-thirty-two');
  const guest = await service.create(request());
  const access = { participantId: guest.credential.participantId, token: guest.credential.token };
  const id = guest.credential.roomId;
  const rename = { commandId: randomBytes(16).toString('hex'), sequence: 1, command: { type: 'rename' as const, nickname: 'Sam' } };
  const before = (await repo.read(id))!.room.revision;
  const deleting = () => requireNotDeleting({ get: async () => ({ requestedAt: 0, purgeAfter: 1, phase: 'pending', recoveryId: 'r' }) } as never, { kind: 'guest', roomId: id, participantId: access.participantId });
  await assert.rejects(service.command(id, access, rename, deleting()), (e: unknown) => e instanceof RoomError && e.code === 'forbidden');
  assert.equal((await repo.read(id))!.room.revision, before, 'nothing committed');
  const applied = await service.command(id, access, rename, Promise.resolve());
  assert.equal(applied.receipt.replayed, false);
  await assert.rejects(service.command(id, access, rename, deleting()), (e: unknown) => e instanceof RoomError && e.code === 'forbidden', 'a replayed receipt is not answered either');
});
