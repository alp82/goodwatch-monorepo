import requests
import shutil
import datetime
import fcntl
import json
import time
from contextlib import contextmanager
import os
from pathlib import Path
from dotenv import load_dotenv

# --- CONFIGURATION ---
# 1. Load Environment Variables
script_dir = Path(__file__).parent
load_dotenv(script_dir / ".env") 

# 2. Get Config from Env
QDRANT_HOST = os.getenv("QDRANT_HOST", "http://10.0.0.20:6333")
API_KEY = os.getenv("QDRANT_API_KEY")
BACKUP_ROOT = Path("/mnt/backup-qdrant/snapshots")
# Local lock: remote SSHFS advisory locking is not needed for job serialization.
BACKUP_LOCK = Path("/run/lock/goodwatch-qdrant-backup.lock")
# ---------------------

# Common Headers for Auth
HEADERS = {
    "api-key": API_KEY
}

def emit_phase(collection_name, phase, status, elapsed_ms=None):
    # Fixed classes, never collection names, paths, exceptions or request data.
    collection_class = {"media_fingerprint_v1": "media", "search_reference_profiles": "reference"}.get(collection_name, "other")
    event = {"event": "qdrant.backup.phase.v1", "at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
             "collectionClass": collection_class, "phase": phase, "status": status}
    if elapsed_ms is not None:
        event["elapsedMs"] = round(elapsed_ms, 3)
    if phase == "cache_advice" and status != "started":
        event["adviceAccepted"] = status == "completed"
    print(json.dumps(event, separators=(",", ":")), flush=True)


@contextmanager
def backup_phase(collection_name, phase):
    started = time.monotonic()
    emit_phase(collection_name, phase, "started")
    try:
        yield
    except Exception:
        emit_phase(collection_name, phase, "failed", (time.monotonic() - started) * 1000)
        raise
    else:
        emit_phase(collection_name, phase, "completed", (time.monotonic() - started) * 1000)


def get_collections():
    try:
        r = requests.get(f"{QDRANT_HOST}/collections", headers=HEADERS)
        r.raise_for_status()
        return [c['name'] for c in r.json()['result']['collections']]
    except Exception as e:
        print(f"Failed to fetch collections: {e}")
        return []

def create_snapshot(collection_name):
    print(f"[{collection_name}] Triggering snapshot...")
    try:
        # wait=true ensures the file is fully written on disk before we move it
        with backup_phase(collection_name, "snapshot"):
            r = requests.post(f"{QDRANT_HOST}/collections/{collection_name}/snapshots?wait=true", headers=HEADERS)
            r.raise_for_status()
            return r.json()['result']['name'] # Returns the raw filename generated by Qdrant
    except Exception as e:
        print(f"[{collection_name}] Snapshot failed: {e}")
        return None

def sync_file(path, release_cache=False):
    """Persist immutable archive data; cache advice never changes its contents."""
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    try:
        os.fsync(fd)
        if release_cache:
            os.posix_fadvise(fd, 0, 0, os.POSIX_FADV_DONTNEED)
    finally:
        os.close(fd)


def sync_directory(directory):
    fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


@contextmanager
def backup_lock():
    fd = os.open(BACKUP_LOCK, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield
    finally:
        os.close(fd)


def rotate_and_clean(collection_name, raw_filename):
    with backup_lock():
        _rotate_and_clean(collection_name, raw_filename)


def _rotate_and_clean(collection_name, raw_filename):
    """Rename hourly archives, link longer retention names, then release cache."""
    directory = BACKUP_ROOT / collection_name
    directory.mkdir(parents=True, exist_ok=True)
    source = directory / raw_filename
    checksum = directory / (raw_filename + ".checksum")
    if not source.exists():
        print(f"[{collection_name}] Snapshot source missing; retention skipped")
        return

    now = datetime.datetime.now()
    timestamp = now.strftime("%Y%m%d_%H%M%S")
    names = [f"hourly_{timestamp}.snapshot"]
    if now.hour == 0:
        names.append(f"daily_{timestamp}.snapshot")
        if now.weekday() == 6:
            names.append(f"weekly_{timestamp}.snapshot")
    sources = [(source, "")]
    if checksum.exists():
        sources.append((checksum, ".checksum"))
    targets = [directory / (name + suffix) for name in names for _, suffix in sources]
    # A retry in the same second must not overwrite an existing recovery point.
    if any(path.exists() or path.is_symlink() for path in targets):
        raise FileExistsError("retention destination already exists")
    with backup_phase(collection_name, "publish"):
        for path, _ in sources:
            sync_file(path)

        moved, linked = [], []
        try:
            for path, suffix in sources:
                retained = directory / (names[0] + suffix)
                path.rename(retained)
                moved.append((path, retained))
            for name in names[1:]:
                for _, suffix in sources:
                    retained = directory / (name + suffix)
                    os.link(directory / (names[0] + suffix), retained)
                    linked.append(retained)
            sync_directory(directory)
            with backup_phase(collection_name, "cache_advice"):
                for _, retained in moved:
                    sync_file(retained, release_cache=True)
        except Exception:
            # Keep all prior recovery points. Restore the raw pair when possible;
            # if rollback itself fails, leave every surviving new alias for recovery.
            try:
                for original, retained in reversed(moved):
                    if original.exists() or original.is_symlink():
                        raise FileExistsError("raw recovery destination already exists")
                    retained.rename(original)
                for retained in linked:
                    retained.unlink()
                sync_directory(directory)
            except OSError:
                print(f"[{collection_name}] Publication rollback incomplete; recovery files retained")
            raise

    for name in names:
        print(f"[{collection_name}] Created {name}")
    # Run retention only after every requested name is durable and advice succeeded.
    with backup_phase(collection_name, "retention"):
        cleanup_files(directory, "hourly_", hours=3)
        cleanup_files(directory, "daily_", days=3)
        cleanup_files(directory, "weekly_", days=21)
        sync_directory(directory)

def cleanup_files(directory, prefix, hours=0, days=0):
    """Deletes files starting with prefix that are older than X hours/days"""
    limit_seconds = (days * 86400) + (hours * 3600)
    now_epoch = datetime.datetime.now().timestamp()

    for f in directory.glob(f"{prefix}*"):
        path_age = now_epoch - f.stat().st_mtime
        if path_age > limit_seconds:
            if f.is_file():
                print(f"Cleaning up old backup: {f.name}")
                f.unlink()
            else:
                print(f"Cleaning up old backup directory: {f.name}")
                shutil.rmtree(f)

if __name__ == "__main__":
    with backup_lock():
        collections = get_collections()
        for col in collections:
            raw_name = create_snapshot(col)
            if raw_name:
                _rotate_and_clean(col, raw_name)
